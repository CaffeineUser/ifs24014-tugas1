import { Router } from 'express';
import { reportController } from '../controllers/reportController.js';
import { supportController } from '../controllers/supportController.js';
import { authenticate, authorize } from '../middleware/auth.js';
import { validate } from '../middleware/validate.js';
import { uploadPhoto } from '../middleware/upload.js';
import { createReportSchema, idParamSchema, reportListSchema, updateReportSchema, updateStatusSchema, updateUrgencySchema, paginationSchema } from '../validators/schemas.js';
const router = Router();
router.get('/', validate(reportListSchema, 'query'), reportController.list);
router.post('/', authenticate, authorize('warga'), uploadPhoto, validate(createReportSchema), reportController.create);
router.get('/:id', validate(idParamSchema, 'params'), reportController.getById);
router.patch('/:id', authenticate, authorize('warga'), validate(idParamSchema, 'params'), validate(updateReportSchema), reportController.updateOwn);
router.delete('/:id', authenticate, authorize('warga'), validate(idParamSchema, 'params'), reportController.deleteOwn);
router.patch('/:id/status', authenticate, authorize('admin'), validate(idParamSchema, 'params'), validate(updateStatusSchema), reportController.updateStatus);
router.patch('/:id/urgency', authenticate, authorize('admin'), validate(idParamSchema, 'params'), validate(updateUrgencySchema), reportController.updateUrgency);
router.patch('/:id/photo', authenticate, authorize('warga'), validate(idParamSchema, 'params'), uploadPhoto, reportController.updatePhoto);
router.get('/:id/history', validate(idParamSchema, 'params'), reportController.history);
router.get('/:id/photo', validate(idParamSchema, 'params'), reportController.photo);
router.get('/:id/supports', validate(idParamSchema, 'params'), validate(paginationSchema, 'query'), supportController.list);
router.post('/:id/supports', authenticate, authorize('warga'), validate(idParamSchema, 'params'), supportController.add);
router.delete('/:id/supports/me', authenticate, authorize('warga'), validate(idParamSchema, 'params'), supportController.remove);
export default router;
